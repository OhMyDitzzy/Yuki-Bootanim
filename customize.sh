#!/system/bin/sh

SKIPUNZIP=0

DATADIR="/data/adb/yuki_bootanim_installer"
CONF="$DATADIR/device.conf"

ui_print " "
ui_print "======================================"
ui_print "   Yuki BootAnimation Installer"
ui_print "======================================"
ui_print " "

if [ "$KSU" = "true" ]; then
  ROOT_MGR="ksu"
  ui_print "- Detected KernelSU / KernelSU Next $KSU_VER"
elif [ "$APATCH" = "true" ]; then
  ROOT_MGR="apatch"
  ui_print "- APatch Detected $APATCH_VER"
elif [ -n "$MAGISK_VER_CODE" ]; then
  ROOT_MGR="magisk"
  ui_print "- Magisk Detected $MAGISK_VER"
  if [ "$MAGISK_VER_CODE" -lt 20400 ]; then
    abort "! This module requires Magisk v20.4 or above"
  fi
else
  ROOT_MGR="unknown"
  ui_print "- [!] Root manager not recognized!!! proceeding assuming compatible, Use with caution!"
fi

# Note: we are NOT distinguishing the official "ksu" from KernelSU Next/SukiSU-Ultra
# here. The $KSU env var is "true" in all of these forks, and
# the difference in whether metamodules are required has been handled more safely with
# a direct write test in apply.sh (see the note there), not through
# guessing the fork name, which cannot always be confirmed through the shell.
DEV_API="$API"
if [ -z "$DEV_API" ]; then
  DEV_API=$(getprop ro.build.version.sdk 2>/dev/null)
fi
if [ -z "$DEV_API" ]; then
  DEV_API=21
  ui_print "- [!] Warning: failed to read API level, fallback to $DEV_API"
else
  ui_print "- Android API level: $DEV_API"
fi

MANUFACTURER=$(getprop ro.product.manufacturer 2>/dev/null | tr '[:upper:]' '[:lower:]')
BRAND=$(getprop ro.product.brand 2>/dev/null | tr '[:upper:]' '[:lower:]')

IS_SAMSUNG=false
case "$MANUFACTURER $BRAND" in
  *samsung*) IS_SAMSUNG=true ;;
esac

if [ "$IS_SAMSUNG" = "true" ]; then
  ui_print "- Samsung device detected -> boot animation mode .qmg"
else
  ui_print "- Non-Samsung devices -> standard .zip boot animation mode"
fi

HAS_METAMODULE=false
METAMODULE_NAME=""
if [ -e "/data/adb/metamodule" ]; then
  HAS_METAMODULE=true
  METAMODULE_NAME=$(basename "$(readlink -f /data/adb/metamodule 2>/dev/null)" 2>/dev/null)
  ui_print "- Metamodule installed: ${METAMODULE_NAME:-tidak diketahui namanya}"
fi

mkdir -p "$DATADIR/backup" "$DATADIR/staging" 2>/dev/null

cat > "$CONF" << EOF
# Automatically generated by customize.sh during module installation/update.
# DO NOT EDIT manually — remove the module and reinstall it for re-detection.
ROOT_MGR=$ROOT_MGR
API=$DEV_API
IS_SAMSUNG=$IS_SAMSUNG
HAS_METAMODULE=$HAS_METAMODULE
METAMODULE_NAME=$METAMODULE_NAME
# Legacy single-path field, kept for backward compatibility. apply.sh
# actually picks the real install target out of ROM_MEDIA_CANDIDATES below.
SYSTEM_MEDIA=/system/media
# Space-separated, most-likely-first. Different ROMs keep their boot
# animation under different partitions depending on partition layout
# (system-as-root, split /product, A/B, etc). Kept identical to apply.sh's
# own inline fallback default so behavior doesn't depend on whether
# device.conf happens to be readable.
ROM_MEDIA_CANDIDATES="/product/media /product/etc/media /oem/media /system/media /system/product/media"
EOF

chmod 0644 "$CONF" 2>/dev/null

if [ -f "$MODPATH/common/apply.sh" ]; then
  cp -f "$MODPATH/common/apply.sh" "$MODPATH/apply.sh"
  chmod 0755 "$MODPATH/apply.sh"
fi

ui_print " "
ui_print "- Setup is complete. Reboot, then open this module from"
ui_print "  manager to select boot animation via WebUI."
ui_print " "